const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const slugify = (s) =>
  String(s).replace(/\+/g, " plus ").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// "1.5 dCi 90" → diesel, 1500 cc, 90 hp. Unknown parts stay null.
function engineInfo(name) {
  const n = name.toLowerCase();
  let fuel = "petrol";
  if (/hybrid|e-tech|e-power/.test(n)) fuel = "hybrid";
  else if (/electric|ë-|^e-\d/.test(n)) fuel = "electric";
  else if (/dci|hdi|tdi|sdi|cdi|crdi|d-4d|multijet|jtd|tdci|ecoblue|cdti|\bdti\b|\bdi\b|ddis|di-d|ddi|\btd\b|\bd\b|\d+d\b|dti|dtec|ctdi|bluetec|\bcrd\b|mz-cd|\btci\b|\btd[v]?\d|\bsd[v]?\d|\bd\d{1,3}\b|skyactiv-d|\d+tds?\b/.test(n)) fuel = "diesel";
  const disp = name.match(/^(\d\.\d{1,2})\b/) || name.match(/\b(\d\.\d)\b/);
  const cc = disp ? Math.round(Number(disp[1]) * 1000 / 10) * 10 : null;
  const hp = name.match(/(\d{2,3})\s*$/);
  return { fuel, cc, hp: hp ? Number(hp[1]) : null };
}

const lines = readFileSync(join(here, "vehicles-morocco.txt"), "utf8").split("\n");
const sql = [
  "-- Generated by infra/d1/catalog/build-seed.mjs from vehicles-morocco.txt — do not edit by hand.",
  "-- Safe to run again: existing rows are kept (INSERT OR IGNORE).",
  "",
];
let make = null;
let model = null;
let genOrder = 0;
const counts = { makes: 0, models: 0, generations: 0, engines: 0 };

for (const raw of lines) {
  const line = raw.trim();
  if (!line || line.startsWith("#")) continue;
  const [kind, ...cols] = line.split("|").map((c) => c.trim());
  if (kind === "make") {
    make = cols[0];
    sql.push(`\n-- ${cols[1]}`, `INSERT OR IGNORE INTO vehicle_makes (slug, name) VALUES (${q(make)}, ${q(cols[1])});`);
    counts.makes++;
  } else if (kind === "model") {
    model = cols[0];
    genOrder = 0;
    sql.push(`INSERT OR IGNORE INTO vehicle_models (make_id, slug, name) SELECT id, ${q(model)}, ${q(cols[1])} FROM vehicle_makes WHERE slug = ${q(make)};`);
    counts.models++;
  } else if (kind === "gen") {
    const [name, from, to, engines] = cols;
    const gslug = slugify(name);
    const where = `JOIN vehicle_makes mk ON mk.id = vm.make_id WHERE mk.slug = ${q(make)} AND vm.slug = ${q(model)}`;
    sql.push(
      `INSERT OR IGNORE INTO vehicle_generations (model_id, slug, name, year_start, year_end, sort_order) SELECT vm.id, ${q(gslug)}, ${q(name)}, ${Number(from)}, ${to ? Number(to) : "NULL"}, ${genOrder++} FROM vehicle_models vm ${where};`
    );
    // Years for the buyer's vehicle picker (make → model → year).
    sql.push(
      `INSERT OR IGNORE INTO vehicle_years (model_id, year) WITH RECURSIVE y(n) AS (SELECT ${Number(from)} UNION ALL SELECT n + 1 FROM y WHERE n < ${to ? Number(to) : CURRENT_YEAR}) SELECT vm.id, n FROM y, vehicle_models vm ${where};`
    );
    counts.generations++;
    for (const engine of String(engines || "").split(";").map((e) => e.trim()).filter(Boolean)) {
      const { fuel, cc, hp } = engineInfo(engine);
      sql.push(
        `INSERT OR IGNORE INTO vehicle_engines (generation_id, slug, name, fuel, displacement_cc, power_hp) SELECT g.id, ${q(slugify(engine))}, ${q(engine)}, ${q(fuel)}, ${cc ?? "NULL"}, ${hp ?? "NULL"} FROM vehicle_generations g JOIN vehicle_models vm ON vm.id = g.model_id ${where} AND g.slug = ${q(gslug)};`
      );
      counts.engines++;
    }
  }
}

sql.push("\n-- Part brands common in Morocco");
for (const b of BRANDS) sql.push(`INSERT OR IGNORE INTO brands (slug, name) VALUES (${q(slugify(b))}, ${q(b)});`);

writeFileSync(out, sql.join("\n") + "\n");
console.log(`${out}: ${counts.makes} makes, ${counts.models} models, ${counts.generations} generations, ${counts.engines} engines, ${BRANDS.length} brands`);
